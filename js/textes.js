/**
 * Texte de la clé, avec les {valeurs} remplacées. Clé inconnue : la clé elle-même (visible, donc repérable).
 */
export function t(cle, valeurs = {}) {
  const modele = FR[cle] ?? cle;
  return modele.replace(/\{(\w+)\}/g, (tout, nom) => (nom in valeurs ? String(valeurs[nom]) : tout));
}

export function aUnTexte(cle) {
  return cle in FR;
}

